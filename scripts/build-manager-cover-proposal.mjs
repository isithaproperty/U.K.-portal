/** Generate reviewable SQL from Nov 17 read-only London catalog definitions. No connection. */
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const snapshot=JSON.parse(await readFile('tests/fixtures/manager-cover-production-definitions.json','utf8'));
// Production approval for the separate H&S correction is a prerequisite. Do not combine implicitly.
const safety=JSON.parse(await readFile('tests/fixtures/manager-cover-after-safety-predicates.json','utf8'));
for(const p of snapshot.policies.filter(p=>p.schema==='storage')){const corrected=safety.find(s=>s.name===p.name);if(!corrected)throw Error('Missing reviewed H&S prerequisite');p.qual=corrected.qual;p.check=corrected.check;}
const q=s=>"'"+s.replaceAll("'","''")+"'",ident=s=>'"'+s.replaceAll('"','""')+'"';
const md5=s=>createHash('md5').update(s).digest('hex');
function cover(s){return s?.replace(/nullif\(m\.portfolio_manager,\s*''(?:::text)?\)\s*=\s*b\.manager/gi,'public.manager_portfolio_matches(m.email,m.portfolio_manager,b.manager)').replace(/m\.portfolio_manager\s*=\s*((?:b|blocks)\.manager)/g,(_,target)=>`public.manager_portfolio_matches(m.email,m.portfolio_manager,${target})`).replace(/b\.manager\s*=\s*m\.portfolio_manager/g,'public.manager_portfolio_matches(m.email,m.portfolio_manager,b.manager)');}
const helper=`create function public.manager_portfolio_matches(p_email text,p_own text,p_target text) returns boolean
language sql immutable parallel safe security invoker set search_path='' as $cover$
 select coalesce(length(btrim(p_own))>0 and length(btrim(p_target))>0 and (
 p_own=p_target
 or (p_email='ramiro@aviaf.co.uk' and p_own='Ramiro Naidoo' and p_target='Jillian')
 or (p_email='jillian@aviaf.co.uk' and p_own='Jillian' and p_target='Ramiro Naidoo')),false);
$cover$;
revoke all on function public.manager_portfolio_matches(text,text,text) from public,anon;
grant execute on function public.manager_portfolio_matches(text,text,text) to authenticated,service_role;
`;
let sql=`-- PROPOSAL ONLY: requires explicit production security approval. London yhyqxvbquavhndxcwttt.
-- Generated by scripts/build-manager-cover-proposal.mjs from read-only catalog definitions.
-- Changes manager scope only; roles, financial rows and object bytes are preserved.
-- REQUIRES the separately approved H&S policy correction first. Guards reject the broken original policies.
begin;
set local lock_timeout='5s';set local statement_timeout='30s';
${helper}\n`;
let rollback='-- Restore exact pre-cover definitions. No business rows or Storage files are restored.\nbegin;\n';
for(const p of snapshot.policies){
 const target=`${ident(p.schema)}.${ident(p.table)}`;
 // Guard the reviewed policy's command, roles and both predicates. Fail atomically on drift.
 sql+=`do $guard$ begin if not exists(select 1 from pg_catalog.pg_policies where schemaname=${q(p.schema)} and tablename=${q(p.table)} and policyname=${q(p.name)} and cmd=${q(p.cmd)} and roles::text[]=${q('{'+p.roles.join(',')+'}')}::text[] and qual is not distinct from ${p.qual===null?'null':q(p.qual)} and with_check is not distinct from ${p.check===null?'null':q(p.check)}) then raise exception 'Reviewed policy changed: ${p.name}'; end if; end $guard$;\n`;
 const statement=transform=>`alter policy ${ident(p.name)} on ${target}${p.qual?' using ('+transform(p.qual)+')':''}${p.check?' with check ('+transform(p.check)+')':''};\n`;
 const changed=statement(cover);if(changed.includes('m.portfolio_manager ='))throw Error('Unconverted policy '+p.name);
 sql+=changed;rollback+=statement(s=>s);
}
for(const f of snapshot.functions){
 const updated=cover(f.definition);if(updated===f.definition)throw Error('No comparison converted '+f.name);
 sql+=`do $guard$ begin if not exists(select 1 from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid=p.pronamespace where n.nspname=${q(f.schema)} and p.proname=${q(f.name)} and pg_catalog.pg_get_function_identity_arguments(p.oid)=${q(f.identity)} and md5(pg_catalog.pg_get_functiondef(p.oid))=${q(md5(f.definition))}) then raise exception 'Reviewed function changed: ${f.schema}.${f.name}'; end if; end $guard$;\n${updated};\n`;
 rollback+=f.definition+';\n';
}
// Extending both UPDATE predicates must not let managers reassign blocks between portfolios.
sql+=`create function private.prevent_manager_block_reassignment() returns trigger
language plpgsql security invoker set search_path='' as $cover$
begin
 if new.manager is distinct from old.manager and exists(select 1 from public.portal_members m where m.email=lower(auth.jwt()->>'email') and m.role='manager') then
 raise exception 'Only an owner or admin can reassign the manager' using errcode='42501';
 end if;
 return new;
end $cover$;
revoke all on function private.prevent_manager_block_reassignment() from public,anon,authenticated,service_role;
create trigger prevent_manager_block_reassignment before update of manager on public.blocks for each row execute function private.prevent_manager_block_reassignment();
commit;\n`;
rollback+=`drop trigger prevent_manager_block_reassignment on public.blocks;
drop function private.prevent_manager_block_reassignment();
drop function public.manager_portfolio_matches(text,text,text);
commit;\n`;
await writeFile('docs/proposed-named-manager-cover.sql',sql);await writeFile('docs/rollback-named-manager-cover.sql',rollback);
console.log(`Generated ${snapshot.policies.length} policy amendments, ${snapshot.functions.length} function replacements, scope helper and reassignment guard; no hosted connection.`);
